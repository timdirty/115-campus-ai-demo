#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import {apps, appUrl, rootDir} from './app-catalog.mjs';

const docsDir = path.join(rootDir, 'docs');
const outputPath = path.join(docsDir, 'JUDGE_ONE_PAGER.md');
const publicBase = 'https://timdirty.github.io/115-campus-ai-demo';

const rows = apps.map((app) => (
  `| ${app.team} | ${app.name} | ${app.desc} | ${app.flow.join(' -> ')} | ${app.ev3.role} | ${publicBase}/${appUrl(app)} |`
)).join('\n');

const text = `# Judge One Pager

Generated by \`npm run demo:judge\`. This is the short version for teachers, judges, and parents who need the whole workspace story quickly.

## Core Story

Three independent student teams built three separate campus AI apps in one workspace. The apps share development checks, deployment tooling, and a hardware bridge, but each team has its own route, story, demo flow, and EV3 role.

## Three Teams

| Team | Project | Problem solved | Demo flow | EV3 role | Public route |
| --- | --- | --- | --- | --- | --- |
${rows}

## What AI Does

- App 1 analyzes whiteboard/camera input and turns it into keep/erase teaching decisions.
- App 2 analyzes campus service scenes and turns them into delivery, cleaning, patrol, or safety tasks.
- App 3 analyzes mood text, acoustic signals, and privacy-preserving visual cues for care recommendations.

## What Hardware Does

- Arduino UNO R4 receives the shared serial command catalog for display, sensor, and robot demo actions.
- LEGO EV3 receives \`EV3_*\` commands through the App 1 bridge and EV3 WebSocket server.
- \`DEMO_SIMULATE_HARDWARE=1\` keeps the same command path available when real hardware is not connected.

## Verification Evidence

- \`npm run demo:ready\` verifies three app checks, firmware builds, EV3 catalog, GitHub Pages artifact, and responsive layouts.
- \`docs/DEMO_EVIDENCE.md\` records the latest readiness evidence.
- \`docs/EV3_FIELD_TEST_REPORT.md\` records EV3 host reachability and the command checklist.
- \`docs/DEMO_SCORECARD.md\` and \`docs/REHEARSAL_RUNBOOK.md\` guide timed student rehearsal.

## Best Short Answer

「這不是三個靜態展示頁，而是三個獨立作品：各自有 AI/本機辨識、自己的任務流程、自己的 EV3 角色，也有 no-network/no-hardware 的現場備援。每次上台前我們用 \`npm run demo:ready\` 做完整驗收。」
`;

fs.mkdirSync(docsDir, {recursive: true});
fs.writeFileSync(outputPath, text, 'utf8');
console.log('Judge one pager generated: docs/JUDGE_ONE_PAGER.md');
