#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import {apps, rootDir} from './app-catalog.mjs';

const docsDir = path.join(rootDir, 'docs');
const scorecardPath = path.join(docsDir, 'DEMO_SCORECARD.md');

function minuteFlow(app) {
  return app.flow.map((step, index) => `${index + 1}. ${step}`).join('\n');
}

function appScorecard(app) {
  const mustShowItems = app.scorecardMustShow ?? [
    `Student performs the core flow: ${app.flow.join(' -> ')}.`,
    'Student points to one AI or local-analysis result and explains what input changed the result.',
    `Student names the EV3 role: ${app.ev3.role}.`,
    'Student can explain the fallback: no network, no EV3, no Arduino still leaves a complete demo path.',
  ];
  const mustShowLines = [
    '- [ ] App opens from its own route; student names the team without using another team\'s screen.',
    ...mustShowItems.map((item) => `- [ ] ${item}`),
  ].join('\n');

  return `## ${app.team} - ${app.name}

### 60 Second Proof Flow

${minuteFlow(app)}

### Must Show

${mustShowLines}

### Evidence To Mention

| Evidence | What to say |
| --- | --- |
| AI / local analysis | The app turns real input into a decision, not a fixed slide. |
| EV3 command path | The app uses ${app.ev3.commands.map((command) => `\`${command}\``).join(', ')}. |
| Safety fallback | \`DEMO_SIMULATE_HARDWARE=1\` keeps the same command flow when hardware is not attached. |

### Pass Criteria

- [ ] Core flow completes in 60 seconds.
- [ ] One student can answer "AI 真的做了什麼？"
- [ ] One student can answer "EV3 怎麼接？"
- [ ] One student can answer "硬體壞掉怎麼辦？"
- [ ] No horizontal scrolling or clipped buttons on phone/tablet/desktop readiness checks.
`;
}

const text = `# Demo Scorecard

Generated by \`npm run demo:scorecard\`. Use this as the final team-by-team scoring sheet before a class rehearsal, competition demo, or teacher review.

## Whole Workspace Gate

- [ ] \`npm run demo:ready\` finishes with \`Competition readiness check passed\`.
- [ ] \`docs/DEMO_EVIDENCE.md\` is regenerated after the latest readiness run.
- [ ] \`demo-ready-report.json\` lists all three apps.
- [ ] GitHub Pages routes are checked after deployment with \`npm run check:public\`.
- [ ] Hardware fallback is rehearsed once with \`DEMO_SIMULATE_HARDWARE=1 npm run dev\`.

${apps.map(appScorecard).join('\n')}

## Final Teacher Sign-Off

- [ ] Each team can demo independently without borrowing another team's story.
- [ ] Each team has a clear AI explanation, a hardware explanation, and a fallback explanation.
- [ ] Students can recover from camera, network, EV3, or Arduino failure without stopping the presentation.
- [ ] Latest generated docs include \`DEMO_READY.md\`, \`FIELD_CHECKLIST.md\`, \`STUDENT_PITCHES.md\`, \`JUDGE_QA.md\`, \`DEMO_EVIDENCE.md\`, and \`DEMO_SCORECARD.md\`.
`;

fs.mkdirSync(docsDir, {recursive: true});
fs.writeFileSync(scorecardPath, text, 'utf8');
console.log('Demo scorecard generated: docs/DEMO_SCORECARD.md');
