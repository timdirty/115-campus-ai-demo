#!/usr/bin/env node

import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {apps, rootDir} from './app-catalog.mjs';

const docsDir = path.join(rootDir, 'docs');
const outputPath = path.join(docsDir, 'EV3_FIELD_TEST_REPORT.md');

function tcpProbe(host, port, timeoutMs = 800) {
  return new Promise((resolve) => {
    const socket = net.createConnection({host, port});
    const startedAt = Date.now();
    const timer = setTimeout(() => {
      socket.destroy();
      resolve({host, port, reachable: false, latencyMs: null, message: 'timeout'});
    }, timeoutMs);
    socket.once('connect', () => {
      clearTimeout(timer);
      socket.destroy();
      resolve({host, port, reachable: true, latencyMs: Date.now() - startedAt, message: 'tcp reachable'});
    });
    socket.once('error', (error) => {
      clearTimeout(timer);
      resolve({host, port, reachable: false, latencyMs: null, message: error.code || error.message});
    });
  });
}

function candidateHosts() {
  return [
    ...(process.env.EV3_HOSTS ?? '').split(',').map((item) => item.trim()).filter(Boolean),
    process.env.EV3_HOST || '192.168.0.1',
    'ev3dev.local',
  ].map((host) => host.replace(/^wss?:\/\//, '').replace(/:\d+\/?$/, ''));
}

function verifyCatalog() {
  const result = spawnSync('node', ['scripts/verify-ev3-catalog.mjs'], {cwd: rootDir, encoding: 'utf8'});
  return {
    ok: result.status === 0,
    output: (result.stdout || result.stderr || '').trim(),
  };
}

function commandRows() {
  return apps.flatMap((app) => app.ev3.commands.map((command) => {
    const safety = command === 'EV3_STOP' || command === 'EV3_CANCEL' || command === 'EV3_SAFE_POSE'
      ? 'Safety / immediate stop path'
      : command === 'EV3_STATUS'
        ? 'Read-only health check'
        : 'Motion command; test after STOP is verified';
    return `| ${app.team} | ${command} | ${app.ev3.role} | ${safety} |`;
  })).join('\n');
}

function hostRows(probes) {
  return probes.map((probe) => (
    `| ${probe.host}:${probe.port} | ${probe.reachable ? 'reachable' : 'not reachable'} | ${probe.latencyMs ?? '--'} | ${probe.message} |`
  )).join('\n');
}

async function main() {
  const generatedAt = new Date().toISOString();
  const catalog = verifyCatalog();
  const probes = [];
  for (const host of [...new Set(candidateHosts())]) {
    probes.push(await tcpProbe(host, 8765));
  }
  const reachable = probes.find((probe) => probe.reachable);

  const text = `# EV3 Field Test Report

Generated: ${generatedAt}

This report is regenerated by \`npm run demo:ready\`. It records EV3 readiness without adding extra dependencies. When an EV3 brick is reachable on port 8765, the host probe is recorded here; when it is not connected, this still provides the exact command checklist for field testing.

## Summary

- EV3 catalog verification: ${catalog.ok ? 'passed' : 'failed'}
- EV3 host probe: ${reachable ? `reachable at ${reachable.host}:8765 (${reachable.latencyMs} ms)` : 'not reachable in this environment'}
- Fallback path: \`DEMO_SIMULATE_HARDWARE=1 npm run dev\`
- Server expected on brick: \`python3 ev3/ev3_server.py\`
- Required safety command before motion: \`EV3_STOP\`

## Host Probe

| Host | Status | Latency ms | Message |
| --- | --- | ---: | --- |
${hostRows(probes)}

## Command Checklist

| Team | Command | EV3 role | Field note |
| --- | --- | --- | --- |
${commandRows()}

## Field Procedure

1. Start EV3 brick server with \`python3 ev3/ev3_server.py\`.
2. Run \`npm run check:ev3\` and confirm catalog verification passes.
3. Run \`npm run check:hardware\` and confirm the EV3 WebSocket port is reachable.
4. Test \`EV3_STATUS\`, then \`EV3_STOP\`, before any motion command.
5. Test one team at a time. After every motion command, run \`EV3_STOP\` or \`EV3_SAFE_POSE\`.
6. If host probe is not reachable, use \`DEMO_SIMULATE_HARDWARE=1\` and explain that the same command path is preserved.

## Catalog Output

\`\`\`text
${catalog.output || 'no output'}
\`\`\`
`;

  fs.mkdirSync(docsDir, {recursive: true});
  fs.writeFileSync(outputPath, text, 'utf8');
  console.log('EV3 field test report generated: docs/EV3_FIELD_TEST_REPORT.md');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
