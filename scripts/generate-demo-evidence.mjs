#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import {apps, rootDir} from './app-catalog.mjs';

const generatedAt = new Date().toISOString();
const checks = [
  'GitHub prepublish safety check passed',
  '500-round polish validation passed',
  'App 1 tests/lint/build passed, including whiteboard pixel quality validation and hardware simulation',
  'App 2 tests/lint/build passed, including campus vision quality validation',
  'App 3 tests/lint/build passed, including privacy vision quality validation',
  'EV3 command catalog matched App catalog and EV3 brick server',
  'EV3 field report generated with host probe and command checklist',
  'PlatformIO firmware build passed for UNO R4 WiFi, UNO R4 Minima, and sensor firmware env',
  'GitHub Pages artifact check passed',
  'Phone, tablet, and desktop responsive layout checks passed',
];

const appRows = apps.map((app) => (
  `| ${app.team} | ${app.name} | ${app.flow.join(' -> ')} | ${app.ev3.role} | ${app.ev3.commands.join(', ')} |`
)).join('\n');

const text = `# Demo Evidence

Generated: ${generatedAt}

This file is regenerated by \`npm run demo:ready\` after the full readiness gate passes. It is meant for student portfolios, competition submission notes, and final teacher review.

## Verified Checks

${checks.map((item) => `- ${item}`).join('\n')}

## Team Evidence

| Team | App | Demo flow | EV3 role | EV3 commands |
| --- | --- | --- | --- | --- |
${appRows}

## Real-Use Proof Points

- Camera/image workflows include local pixel analysis and frame-quality hints for low light, overexposure, low-information frames, and likely blur.
- Hardware workflows include both real bridge paths and \`DEMO_SIMULATE_HARDWARE=1\` fallback.
- Hardware wiring and EV3 field readiness are documented in \`HARDWARE_WIRING_MAP.md\` and \`EV3_FIELD_TEST_REPORT.md\`.
- Rehearsal workflows include reset instructions and timed judge drills in \`REHEARSAL_RUNBOOK.md\`.
- Public deployment is checked locally through the Pages artifact; after deployment run \`npm run check:public\`.
- Field documents are generated: \`DEMO_READY.md\`, \`FIELD_CHECKLIST.md\`, \`STUDENT_PITCHES.md\`, \`JUDGE_QA.md\`, \`JUDGE_ONE_PAGER.md\`, \`DEMO_SCORECARD.md\`, \`REHEARSAL_RUNBOOK.md\`, \`HARDWARE_WIRING_MAP.md\`, and \`EV3_CALIBRATION_TABLE.md\`.
`;

fs.writeFileSync(path.join(rootDir, 'docs/DEMO_EVIDENCE.md'), text, 'utf8');
console.log('Demo evidence generated: docs/DEMO_EVIDENCE.md');
