#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import {apps, rootDir} from './app-catalog.mjs';

const docsDir = path.join(rootDir, 'docs');
const outputPath = path.join(docsDir, 'HARDWARE_WIRING_MAP.md');

const appRows = apps.map((app) => (
  `| ${app.team} | ${app.name} | Browser app -> bridge :${app.bridgePort} | ${app.ev3.role} | ${app.ev3.commands.join(', ')} |`
)).join('\n');

const portRows = apps.map((app) => (
  `| ${app.shortName} frontend | http://localhost:${app.devPort}/ | ${app.name} |
| ${app.shortName} bridge | http://localhost:${app.bridgePort}/ | Independent hardware gateway |`
)).join('\n');

const text = `# Hardware Wiring Map

Generated by \`npm run demo:wiring\`. This is the single-page wiring and fallback reference for the three independent apps.

## Topology

\`\`\`text
Student browser
  ├─ App 1 /app1  ──► localhost:3201 App 1 bridge ─┐
  ├─ App 2 /app2  ──► localhost:3202 App 2 bridge  ├─ USB Serial -> Arduino UNO R4
  └─ App 3 /app3  ──► localhost:3203 App 3 bridge ─┘
  App 1 bridge also  ──► WebSocket ws://EV3_HOST:8765 -> LEGO EV3 ev3dev server
\`\`\`

## Ports And Services

| Item | Value | Notes |
| --- | --- | --- |
${portRows}
| Arduino serial | 115200 baud | UNO R4 command catalog |
| EV3 WebSocket | ws://EV3_HOST:8765 | ev3dev Python server (via App 1 bridge) |
| Hardware simulation | DEMO_SIMULATE_HARDWARE=1 | No-hardware competition fallback |

## Team Wiring

| Team | App | Bridge path | EV3 physical role | EV3 commands |
| --- | --- | --- | --- | --- |
${appRows}

## Field Startup

1. Connect Arduino UNO R4 over USB if using real serial hardware.
2. Start EV3 and run \`python3 ev3/ev3_server.py\` on the brick.
3. Set \`EV3_HOST\` or \`EV3_HOSTS\` if the brick is not at \`192.168.0.1\` or \`ev3dev.local\`.
4. Start local demo with \`DEMO_SIMULATE_HARDWARE=1 npm run dev\` for rehearsal, or \`npm run dev\` for real hardware.
5. Run \`npm run check:hardware\` before students rehearse.

## Failure Recovery

| Failure | Recovery line |
| --- | --- |
| Camera denied | Use upload/sample input and keep the same AI explanation. |
| No Gemini key | Use local fallback analysis and explain the no-network path. |
| Arduino unplugged | Use simulation mode; commands still follow the same bridge path. |
| EV3 unreachable | Use \`DEMO_SIMULATE_HARDWARE=1\`, show \`EV3_FIELD_TEST_REPORT.md\`, and test the brick after network recovery. |
| Public site not deployed yet | Use local Pages artifact from \`npm run demo:ready\`. |
`;

fs.mkdirSync(docsDir, {recursive: true});
fs.writeFileSync(outputPath, text, 'utf8');
console.log('Hardware wiring map generated: docs/HARDWARE_WIRING_MAP.md');
