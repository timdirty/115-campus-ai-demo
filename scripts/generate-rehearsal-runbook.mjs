#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import {apps, appUrl, guideUrl, rootDir} from './app-catalog.mjs';

const docsDir = path.join(rootDir, 'docs');
const outputPath = path.join(docsDir, 'REHEARSAL_RUNBOOK.md');
const publicBase = 'https://timdirty.github.io/115-campus-ai-demo';

function appBlock(app) {
  return `## ${app.team} - ${app.name}

### Student Drill

1. Open \`${publicBase}/${appUrl(app)}\`.
2. Open the guide \`${publicBase}/${guideUrl(app)}\`.
3. Complete the flow in order: ${app.flow.join(' -> ')}.
4. Say one AI evidence sentence.
5. Say one EV3 sentence: ${app.ev3.role}.
6. Say one recovery sentence for camera, network, or hardware failure.

### Reset Before Next Team

- Use the app's visible reset control when available.
- If the browser has stale state, clear this app route's site data and reload.
- Rehearse once with \`DEMO_SIMULATE_HARDWARE=1 npm run dev\` before connecting real EV3 or Arduino.

### Judge Drill

- AI 真的做了什麼？
- EV3 怎麼接？
- 如果沒有網路、沒有相機、沒有 EV3，要怎麼繼續展示？
- 這個作品和另外兩隊哪裡不同？
`;
}

const text = `# Rehearsal Runbook

Generated by \`npm run demo:rehearsal\`. Use this for timed practice before competition day. It focuses on repeatability: reset, rehearse, answer, recover.

## 15 Minute Team Rotation

| Minute | Action |
| --- | --- |
| 0-2 | Run \`npm run demo:ready\` and confirm the latest \`demo-ready-report.json\`. |
| 2-5 | Team 1 runs the 60 second flow and one judge drill. |
| 5-8 | Team 2 runs the 60 second flow and one judge drill. |
| 8-11 | Team 3 runs the 60 second flow and one judge drill. |
| 11-13 | Rehearse one failure: camera denied, network offline, EV3 missing, or Arduino missing. |
| 13-15 | Check \`docs/DEMO_SCORECARD.md\` and mark anything that still needs practice. |

## Reset Contract

- App 1 includes a visible reset for whiteboard demo notes, classroom session, chat, selected note, issue reports, and tour state.
- App 2 includes a visible reset for campus service demo state.
- App 3 includes a visible reset for guardian demo state.
- Root rehearsal evidence is regenerated by \`npm run demo:ready\`.

${apps.map(appBlock).join('\n')}

## Final Pass

- [ ] Every team can finish its 60 second flow without teacher prompting.
- [ ] Every team can explain AI, EV3, and fallback in one sentence each.
- [ ] Every app has been reset once and still opens correctly.
- [ ] Hardware simulation has been rehearsed with \`DEMO_SIMULATE_HARDWARE=1\`.
- [ ] Latest docs include \`DEMO_EVIDENCE.md\`, \`DEMO_SCORECARD.md\`, and \`REHEARSAL_RUNBOOK.md\`.
`;

fs.mkdirSync(docsDir, {recursive: true});
fs.writeFileSync(outputPath, text, 'utf8');
console.log('Rehearsal runbook generated: docs/REHEARSAL_RUNBOOK.md');
